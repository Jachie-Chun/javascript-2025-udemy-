// Crear Arrays "corchetes" ---> [ ]

const numeros = [10, 20, 30, 40, 50];
console.log(numeros); // [10, 20, 30, 40, 50]

// sintaxis poco común
const meses = new Array("Enero", "Febrero", "Marzo", "Abril");
console.log(meses); // ["Enero", "Febrero", "Marzo", "Abril"]

// un array que contiene diferentes tipos de datos
const mixto = [10, "Hola", true, null, undefined, { nombre: "Juan" }, [1, 2, 3]];
console.log(mixto); // [10, "Hola", true, null, undefined, { nombre: "Juan" }, [1, 2, 3]]

